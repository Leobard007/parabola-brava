// parseNumber(value, fallback): turns a text (or number) into a number.
// If it is not a valid number, it returns the fallback.
// Examples: parseNumber('3.5', 0) → 3.5      parseNumber('hello', 0) → 0
function parseNumber(value, fallback) {
  const number = parseFloat(value);
  if (isFinite(number)) {
    return number;
  }
  return fallback;
}

// clampNumber(value, lowest, highest): keeps a number between two limits.
// Example: clampNumber(120, 0, 90) → 90
function clampNumber(value, lowest, highest) {
  return Math.min(highest, Math.max(lowest, value));
}

// snapToStep(value, step): rounds a number to the closest multiple of step.
// Example: snapToStep(3.7, 0.5) → 3.5
function snapToStep(value, step) {
  return Math.round(value / step) * step;
}

// roundToTwoDecimals(value): rounds to 2 decimals. Example: 3.14159 → 3.14
function roundToTwoDecimals(value) {
  return Math.round(value * 100) / 100;
}

// deepCopy(object): makes a full, independent copy of an object, so the copy can be
// changed without changing the original. It works by turning the object into text
// (JSON) and back into a new object.
function deepCopy(object) {
  return JSON.parse(JSON.stringify(object));
}

// formatFixed(number, decimals): the number as text with a fixed number of decimals.
// Very small numbers (like 0.0000000001 or -0) are shown as 0.
// Example: formatFixed(2.5, 2) → "2.50"
function formatFixed(number, decimals) {
  if (decimals === undefined) {
    decimals = 2;
  }
  if (Math.abs(number) < 1e-9) {
    number = 0;
  }
  return number.toFixed(decimals);
}

// formatSigned(number, decimals): like formatFixed, but always with a sign + or −.
// Example: formatSigned(-3) → "−3.00"      formatSigned(4) → "+4.00"
function formatSigned(number, decimals) {
  if (decimals === undefined) {
    decimals = 2;
  }
  let sign = '+';
  if (number < 0) {
    sign = '−'; // typographic minus sign (looks better than "-")
  }
  return sign + formatFixed(Math.abs(number), decimals);
}

// formatNice(number): a "nice" number for people: up to 2 decimals, no extra zeros,
// and the typographic minus sign. Example: formatNice(2.50) → "2.5"   formatNice(-3) → "−3"
function formatNice(number) {
  let rounded = Math.round(number * 100) / 100;
  if (Object.is(rounded, -0)) {
    rounded = 0;
  }
  return rounded.toString().replace('-', '−');
}

// formatNiceSigned(number): like formatNice, but positive numbers get a "+".
function formatNiceSigned(number) {
  if (Math.round(number * 100) / 100 >= 0) {
    return '+' + formatNice(number);
  }
  return formatNice(number);
}

// createUniqueId(): creates an id for a level made in the editor, like "ulq3x9ab12".
// It mixes the current time with random letters so two ids are never the same.
function createUniqueId() {
  const timePart = Date.now().toString(36);
  const randomPart = Math.random().toString(36).slice(2, 6);
  return 'u' + timePart + randomPart;
}

// levelHasVectors(level): true for displacement and mixed levels (the ones with vectors).
function levelHasVectors(level) {
  if (!level) {
    return false;
  }
  return level.type === 'displacement' || level.type === 'mixed';
}

